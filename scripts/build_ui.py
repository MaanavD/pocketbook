"""Wrap ui/app.js for the Desktop app (ES module) and the web dashboard (IIFE). Run after editing ui/app.js."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
app = (ROOT / "ui" / "app.js").read_text()
banner = "// Generated by scripts/build_ui.py from ui/app.js. Edit that file, then rebuild.\n"

desktop = banner + """import { ROUTES_AREA, SIDEBAR_NAV_AREA } from '@hermes/plugin-sdk'
import * as React from 'react'

let api = () => Promise.reject(new Error('not ready'))
let openUrl = () => {}
let onRefreshEvent = () => () => {}

""" + app + """
export default {
  id: 'pocketbook',
  name: 'Finance',
  register (ctx) {
    api = (path, opts) => ctx.rest(path, opts)
    openUrl = url => ctx.os.openExternal(url)
    onRefreshEvent = fn => {
      const offs = ['synced', 'alerts'].map(e => ctx.onEvent(`plugin.pocketbook.${e}`, fn))
      return () => offs.forEach(off => off && off())
    }
    ctx.registerMany([
      { id: 'page', area: ROUTES_AREA, data: { path: '/finance' }, render: () => h(FinanceApp, {}) },
      { id: 'nav', area: SIDEBAR_NAV_AREA, data: { path: '/finance', label: 'Finance', codicon: 'graph' } }
    ])
  }
}
"""

dashboard = banner + """(function () {
  'use strict'
  const SDK = window.__HERMES_PLUGIN_SDK__
  if (!SDK || !window.__HERMES_PLUGINS__) return
  const React = SDK.React
  const api = (path, opts) => SDK.fetchJSON('/api/plugins/pocketbook' + path, opts && opts.method
    ? { method: opts.method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(opts.body || {}) }
    : undefined)
  const openUrl = url => window.open(url, '_blank', 'noopener')
  const onRefreshEvent = () => () => {}

""" + app + """
  window.__HERMES_PLUGINS__.register('pocketbook', FinanceApp)
})()
"""

(ROOT / "desktop" / "plugin.js").write_text(desktop)
(ROOT / "dashboard" / "dist" / "index.js").write_text(dashboard)
print("built desktop/plugin.js and dashboard/dist/index.js")
